"""Generate firmware/font.h from Pillow's bundled default font (Aileron, CC0).

Run: python3 firmware/tools/make_font.py
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

EXTRA = "°·→…’‘“”—–"
SMALL_CHARS = [chr(c) for c in range(32, 127)] + list(EXTRA)
BIG_CHARS = list("ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789")
OUT = Path(__file__).resolve().parent.parent / "font.h"


def draw_text(font, size, height, ch):
    img = Image.new("L", (size * 2, height), 0)
    ImageDraw.Draw(img).text((size // 2, 0), ch, font=font, fill=255)
    return img


def draw_missing(font, size, height, ch):
    """Dashes and the arrow are not in the font: draw them at the hyphen's height, 4x supersampled."""
    _, y0, _, y1 = draw_text(font, size, height, "-").getbbox()
    k = 4
    mid = (y0 + y1) / 2 * k
    thick = (y1 - y0) * k
    width = {"–": 0.5, "—": 0.9, "→": 0.8}[ch] * size
    left = size // 2 * k + thick / 2
    right = left + width * k - thick
    big = Image.new("L", (size * 2 * k, height * k), 0)
    d = ImageDraw.Draw(big)
    d.line([(left, mid), (right, mid)], fill=255, width=round(thick))
    if ch == "→":
        head = width * k * 0.28
        d.line([(right - head, mid - head), (right, mid)], fill=255, width=round(thick))
        d.line([(right - head, mid + head), (right, mid)], fill=255, width=round(thick))
    img = big.resize((size * 2, height), Image.BOX)
    return img, round(width + size * 0.12)


def render_font(name, size, chars):
    font = ImageFont.load_default(size=size)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    missing = draw_text(font, size, height, "\ue000").tobytes()
    glyphs = []
    data = []
    for ch in chars:
        img = draw_text(font, size, height, ch)
        advance = round(font.getlength(ch))
        if ch != " " and img.tobytes() == missing:
            img, advance = draw_missing(font, size, height, ch)
        box = img.getbbox()
        if box is None:
            glyphs.append((ord(ch), 0, 0, 0, 0, advance, len(data)))
            continue
        x0, y0, x1, y1 = box
        crop = img.crop(box)
        glyphs.append((ord(ch), x1 - x0, y1 - y0, x0 - size // 2, y0, advance, len(data)))
        data.extend(crop.tobytes())

    lines = []
    lines.append(f"#define {name}_HEIGHT {ascent + descent}")
    lines.append(f"#define {name}_COUNT {len(glyphs)}")
    lines.append(f"static const font_glyph_t {name}_GLYPHS[{len(glyphs)}] = {{")
    for g in glyphs:
        lines.append("    {%d, %d, %d, %d, %d, %d, %d}," % g)
    lines.append("};")
    lines.append(f"static const uint8_t {name}_ALPHA[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    return lines


def main():
    out = [
        "// Generated by firmware/tools/make_font.py from Pillow's default font (Aileron, CC0). Do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    uint16_t code;     // Unicode code point",
        "    uint8_t w, h;      // bitmap size",
        "    int8_t x_off;      // bitmap left edge relative to the pen",
        "    uint8_t y_off;     // bitmap top relative to the line top",
        "    uint8_t advance;",
        "    uint32_t offset;   // into the ALPHA array",
        "} font_glyph_t;",
        "",
    ]
    out += render_font("FONT_SMALL", 26, SMALL_CHARS)
    out.append("")
    out += render_font("FONT_BIG", 72, BIG_CHARS)
    OUT.write_text("\n".join(out) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
